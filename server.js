app.get('/api/products',async(req,res)=>{
  try{const {rows}=await pool.query('SELECT * FROM public.products WHERE active=1 ORDER BY id DESC');res.json(rows)}
  catch(e){console.error(e);res.status(500).json({error:'Unable to load products.'})}
});

app.post('/api/orders',async(req,res)=>{
  const {customer_name,phone,address,payment,note,items}=req.body;
  if(!customer_name||!phone||!address||!payment||!Array.isArray(items)||!items.length)return res.status(400).json({error:'Please complete all required fields.'});
  const client=await pool.connect();
  try{
    await client.query('BEGIN');
    let total=0,normalized=[];
    for(const i of items){
      const {rows}=await client.query('SELECT * FROM public.products WHERE id=$1 AND active=1 FOR UPDATE',[i.id]);
      const p=rows[0]; const qty=Math.max(1,Math.floor(Number(i.qty)||1));
      if(!p)throw new Error('A product is unavailable.');
      if(Number(p.stock)<qty)throw new Error(`Only ${p.stock} units of ${p.name} are available.`);
      total+=Number(p.price)*qty; normalized.push({id:p.id,name:p.name,price:p.price,qty});
    }
    const order=await client.query('INSERT INTO public.orders(customer_name,phone,address,payment,note,items_json,total) VALUES($1,$2,$3,$4,$5,$6,$7) RETURNING id',[customer_name,phone,address,payment,note||'',JSON.stringify(normalized),total]);
    for(const i of normalized)await client.query('UPDATE public.products SET stock=stock-$1 WHERE id=$2',[i.qty,i.id]);
    await client.query('COMMIT');
    res.json({ok:true,order_id:order.rows[0].id,total,money:money(total)});
  }catch(e){await client.query('ROLLBACK');res.status(400).json({error:e.message||'Could not place order.'})}
  finally{client.release()}
});

