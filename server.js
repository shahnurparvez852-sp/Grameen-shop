const express=require('express');
const session=require('express-session');
const multer=require('multer');
const {Pool}=require('pg');
const {v2:cloudinary}=require('cloudinary');
const path=require('path');

const app=express();
const PORT=process.env.PORT||3000;

if(!process.env.DATABASE_URL){console.warn('WARNING: DATABASE_URL is not set. Add your Supabase Session Pooler connection string in Render Environment Variables.');}
const pool=new Pool({
  connectionString:process.env.DATABASE_URL,
  ssl:process.env.DATABASE_URL?{rejectUnauthorized:false}:undefined,
  max:5,
  idleTimeoutMillis:30000,
  connectionTimeoutMillis:10000
});

app.use(express.json({limit:'2mb'}));
app.use(express.urlencoded({extended:true}));
app.use(session({secret:process.env.SESSION_SECRET||'dev-secret-change-me',resave:false,saveUninitialized:false,cookie:{httpOnly:true,sameSite:'lax'}}));
