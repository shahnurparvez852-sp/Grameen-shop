app.get('/api/admin/me',(req,res)=>res.json({loggedIn:!!req.session.admin}));
app.get('/api/admin/orders',admin,async(req,res)=>{try{const {rows}=await pool.query('SELECT * FROM public.orders ORDER BY id DESC');res.json(rows.map(o=>({...o,items:JSON.parse(o.items_json)})))}catch(e){res.status(500).json({error:'Unable to load orders.'})}});
app.patch('/api/admin/orders/:id',admin,async(req,res)=>{const allowed=['Pending','Confirmed','Packed','Shipped','Delivered','Cancelled'];if(!allowed.includes(req.body.status))return res.status(400).json({error:'Invalid status'});try{await pool.query('UPDATE public.orders SET status=$1 WHERE id=$2',[req.body.status,req.params.id]);res.json({ok:true})}catch(e){res.status(400).json({error:e.message})}});

function uploadToCloudinary(file){return new Promise((resolve,reject)=>{if(!process.env.CLOUDINARY_CLOUD_NAME||!process.env.CLOUDINARY_API_KEY||!process.env.CLOUDINARY_API_SECRET)return reject(new Error('Cloudinary is not configured.'));const stream=cloudinary.uploader.upload_stream({folder:'grameen-shop/products',resource_type:'image'},(error,result)=>error?reject(error):resolve(result.secure_url));stream.end(file.buffer)})}

app.post('/api/admin/products',admin,upload.single('image'),async(req,res)=>{
  try{
    const {name,category,price,old_price,icon,stock}=req.body;
    if(!name||!category||!price)return res.status(400).json({error:'Name, category and price are required.'});
    let image_url='';if(req.file)image_url=await uploadToCloudinary(req.file);
    const r=await pool.query('INSERT INTO public.products(name,category,price,old_price,icon,image_url,stock) VALUES($1,$2,$3,$4,$5,$6,$7) RETURNING id',[name,category,Number(price),Number(old_price||0),icon||'🛍️',image_url,Number(stock||0)]);
    res.json({ok:true,id:r.rows[0].id,image_url});
  }catch(err){res.status(400).json({error:err.message||'Image upload failed.'})}
});

app.patch('/api/admin/products/:id',admin,upload.single('image'),async(req,res)=>{
  try{
    const old=await pool.query('SELECT * FROM public.products WHERE id=$1',[req.params.id]);if(!old.rows[0])return res.status(404).json({error:'Not found'});
    const p=old.rows[0],x={...p,...req.body};let image_url=x.image_url||p.image_url||'';if(req.file)image_url=await uploadToCloudinary(req.file);
    await pool.query('UPDATE public.products SET name=$1,category=$2,price=$3,old_price=$4,icon=$5,image_url=$6,stock=$7,active=$8 WHERE id=$9',[x.name,x.category,Number(x.price),Number(x.old_price||0),x.icon||'🛍️',image_url,Number(x.stock||0),String(x.active)==='1'||x.active===true?1:0,req.params.id]);
    res.json({ok:true,image_url});
  }catch(err){res.status(400).json({error:err.message||'Image update failed.'})}
});
app.delete('/api/admin/products/:id',admin,async(req,res)=>{try{await pool.query('UPDATE public.products SET active=0 WHERE id=$1',[req.params.id]);res.json({ok:true})}catch(e){res.status(400).json({error:e.message})}});

app.use((err,req,res,next)=>{if(err instanceof multer.MulterError)return res.status(400).json({error:err.code==='LIMIT_FILE_SIZE'?'Image must be 5MB or smaller.':err.message});if(err)return res.status(400).json({error:err.message||'Request failed.'});next()});

initDb().then(()=>app.listen(PORT,()=>console.log(`Grameen Shop running on port ${PORT}`))).catch(err=>{console.error('Database initialization failed:',err);process.exit(1)});
